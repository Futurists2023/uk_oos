-- Creates the 3 core tables for the 24/7 UK Stockist & OOS Intelligence Engine.

CREATE TABLE IF NOT EXISTS public.stores (
    domain TEXT NOT NULL,
    brand TEXT NOT NULL,
    platform TEXT,
    brand_url TEXT,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_product_count INTEGER DEFAULT 0,
    PRIMARY KEY (domain, brand)
);

CREATE TABLE IF NOT EXISTS public.skus (
    sku_key TEXT PRIMARY KEY,
    domain TEXT NOT NULL,
    brand TEXT NOT NULL,
    product_title TEXT NOT NULL,
    variant_title TEXT NOT NULL,
    normalized_product_key TEXT NOT NULL,
    product_url TEXT,
    sku_code TEXT,
    current_price NUMERIC(10, 2),
    compare_at_price NUMERIC(10, 2),
    last_in_stock_price NUMERIC(10, 2),
    currency TEXT DEFAULT 'GBP',
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    is_listed BOOLEAN NOT NULL DEFAULT TRUE,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    first_seen_oos_at TIMESTAMPTZ,
    last_seen_in_stock_at TIMESTAMPTZ,
    silent_removed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.stock_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    domain TEXT NOT NULL,
    brand TEXT NOT NULL,
    sku_key TEXT NOT NULL,
    product_title TEXT NOT NULL,
    variant_title TEXT NOT NULL,
    event_type TEXT NOT NULL,
    old_price NUMERIC(10, 2),
    new_price NUMERIC(10, 2),
    details TEXT
);

CREATE INDEX IF NOT EXISTS idx_skus_brand_domain ON public.skus (brand, domain);
CREATE INDEX IF NOT EXISTS idx_skus_oos ON public.skus (brand, is_available, is_listed);
CREATE INDEX IF NOT EXISTS idx_stock_events_brand ON public.stock_events (brand, occurred_at DESC);
